// MARK: - Clipboard

/// One thing you copied.
struct ClipItem: Identifiable, Equatable, Codable {
    enum Kind: String, Codable { case text, link, image, files }

    var id = UUID().uuidString
    var kind: Kind
    var text: String
    var files: [String] = []
    var image: Data?
    var app: String?
    var date = Date()
    var pinned = false

    var symbol: String {
        switch kind {
        case .text: return "text.alignleft"
        case .link: return "link"
        case .image: return "photo"
        case .files: return "doc"
        }
    }
}

/// A searchable history of what you copy. Off until you turn it on; kept in memory only (pins are
/// saved). Anything a password manager marks as concealed or transient is never recorded.
@MainActor
final class ClipboardService: ObservableObject {
    @Published private(set) var items: [ClipItem] = []
    @Published private(set) var enabled = UserDefaults.standard.bool(forKey: "clipboardEnabled")
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let pins = JSONFile<[ClipItem]>("clipboard-pins.json", directory: LocalData.directory)

    /// Pasteboard types that mean "don't keep this" (nspasteboard.org conventions, 1Password, etc.).
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
                                            "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
                                            "Pasteboard generator type", "net.antelle.keeweb"]

    init() {
        items = pins.load() ?? []
        if AppSettings.isSnapshot { loadSamples() }
        if enabled { start() }
    }

    func enable() {
        enabled = true
        UserDefaults.standard.set(true, forKey: "clipboardEnabled")
        start()
    }

    func disable() {
        enabled = false
        UserDefaults.standard.set(false, forKey: "clipboardEnabled")
        timer?.invalidate()
        timer = nil
        items = items.filter(\.pinned)
    }

    private func start() {
        lastCount = NSPasteboard.general.changeCount
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let board = NSPasteboard.general
        guard board.changeCount != lastCount else { return }
        lastCount = board.changeCount
        let types = Set((board.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.localizedName
        var item: ClipItem?
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .files, text: urls.map(\.lastPathComponent).joined(separator: ", "), files: urls.map(\.path), app: app)
        } else if let string = board.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let kind: ClipItem.Kind = Links.looksLikeURL(string) && !string.contains("\n") ? .link : .text
            item = ClipItem(kind: kind, text: String(string.prefix(20_000)), app: app)
        } else if let image = NSImage(pasteboard: board), let thumb = Self.thumbnail(image) {
            item = ClipItem(kind: .image, text: "Image \(Int(image.size.width))×\(Int(image.size.height))", image: thumb, app: app)
        }
        guard let item else { return }
        items.removeAll { !$0.pinned && $0.kind == item.kind && $0.text == item.text }
        let firstUnpinned = items.firstIndex { !$0.pinned } ?? items.count
        items.insert(item, at: firstUnpinned)
        // Keep 200 unpinned items.
        let unpinned = items.enumerated().filter { !$0.element.pinned }.map(\.offset)
        if unpinned.count > 200 { items.remove(at: unpinned.last!) }
    }

    /// Puts an item back on the clipboard (and moves it to the top).
    func copy(_ item: ClipItem) {
        let board = NSPasteboard.general
        board.clearContents()
        switch item.kind {
        case .files: board.writeObjects(item.files.map { URL(fileURLWithPath: $0) as NSURL })
        case .image: if let data = item.image, let image = NSImage(data: data) { board.writeObjects([image]) }
        default: board.setString(item.text, forType: .string)
        }
        lastCount = board.changeCount
        if !item.pinned, let index = items.firstIndex(of: item) {
            var moved = items.remove(at: index)
            moved.date = Date()
            items.insert(moved, at: items.firstIndex { !$0.pinned } ?? items.count)
        }
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        items.sort { ($0.pinned ? 0 : 1, $1.date) < ($1.pinned ? 0 : 1, $0.date) }
        savePins()
    }

    func delete(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        savePins()
    }

    func clear() {
        items = items.filter(\.pinned)
    }

    private func savePins() {
        guard !AppSettings.isSnapshot else { return }
        pins.save(items.filter(\.pinned))
    }

    static func thumbnail(_ image: NSImage) -> Data? {
        let side: CGFloat = 320
        let scale = min(1, side / max(image.size.width, image.size.height, 1))
        let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
        let thumb = NSImage(size: size)
        thumb.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: size))
        thumb.unlockFocus()
        guard let tiff = thumb.tiffRepresentation else { return nil }
        return NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
    }

    private func loadSamples() {
        enabled = true
        let now = Date()
        items = [
            ClipItem(kind: .text, text: "brew install --cask brim", app: "Ghostty", date: now.addingTimeInterval(-40), pinned: true),
            ClipItem(kind: .link, text: "https://github.com/abhargava14/brim/pull/33", app: "Arc", date: now.addingTimeInterval(-90)),
            ClipItem(kind: .text, text: "Included usage resets on the billing date, not the 1st. Teams seats only show per-seat usage.", app: "Notes", date: now.addingTimeInterval(-600)),
            ClipItem(kind: .text, text: "func compactWidth(for event: IslandEvent.Style?) -> CGFloat", app: "Xcode", date: now.addingTimeInterval(-1800)),
            ClipItem(kind: .files, text: "brim-1a-island-app-icon-1024.svg", files: ["/tmp/brim-1a-island-app-icon-1024.svg"], app: "Finder", date: now.addingTimeInterval(-4000)),
            ClipItem(kind: .text, text: "Standup moved to 9:45 tomorrow", app: "Slack", date: now.addingTimeInterval(-7200)),
        ]
    }
}

// MARK: - Shelf

/// Files parked in the notch: drop them in, drag them out anywhere else.
@MainActor
final class ShelfService: ObservableObject {
    @Published private(set) var files: [URL] = []
    private let file = JSONFile<[String]>("shelf.json", directory: LocalData.directory)

    init() {
        files = (file.load() ?? []).map { URL(fileURLWithPath: $0) }.filter { FileManager.default.fileExists(atPath: $0.path) }
        if AppSettings.isSnapshot, files.isEmpty {
            files = ["Brim Island.dc.html", "launch-notes.md", "island-compact-v3-after.png", "brim-0.4.0.dmg"].map { URL(fileURLWithPath: "/tmp/\($0)") }
        }
    }

    func add(_ urls: [URL]) {
        for url in urls where !files.contains(url) { files.append(url) }
        save()
    }

    func remove(_ url: URL) {
        files.removeAll { $0 == url }
        save()
    }

    func clear() {
        files = []
        save()
    }

    func reveal(_ urls: [URL]) {
        NSWorkspace.shared.activateFileViewerSelecting(urls)
    }

    func airDrop(_ urls: [URL]) {
        NSSharingService(named: .sendViaAirDrop)?.perform(withItems: urls)
    }

    private func save() {
        guard !AppSettings.isSnapshot else { return }
        file.save(files.map(\.path))
    }
}

// MARK: - Launcher

/// The six apps on Home. Defaults to common apps found on this Mac; Edit picks others.
@MainActor
final class LauncherService: ObservableObject {
    @Published private(set) var apps: [URL] = []

    static let candidates = ["com.mitchellh.ghostty", "com.apple.Terminal", "com.googlecode.iterm2", "com.apple.dt.Xcode", "com.microsoft.VSCode",
                             "com.todesktop.230313mzl4w4u92", "com.figma.Desktop", "company.thebrowser.Browser", "com.apple.Safari",
                             "com.google.Chrome", "com.linear", "notion.id", "com.tinyspeck.slackmacgap", "com.apple.Notes", "com.apple.mail"]

    init() {
        if let saved = UserDefaults.standard.stringArray(forKey: "launcherApps"), !AppSettings.isSnapshot {
            apps = saved.map { URL(fileURLWithPath: $0) }.filter { FileManager.default.fileExists(atPath: $0.path) }
        } else {
            apps = Array(Self.candidates.compactMap { NSWorkspace.shared.urlForApplication(withBundleIdentifier: $0) }.prefix(6))
        }
    }

    func launch(_ url: URL) {
        NSWorkspace.shared.openApplication(at: url, configuration: NSWorkspace.OpenConfiguration())
    }

    func choose(replacing old: URL?) {
        let panel = NSOpenPanel()
        panel.allowedContentTypes = [.application]
        panel.directoryURL = URL(fileURLWithPath: "/Applications")
        panel.message = "Choose an app for Home"
        NSApp.activate(ignoringOtherApps: true)
        guard panel.runModal() == .OK, let url = panel.url else { return }
        if let old, let index = apps.firstIndex(of: old) { apps[index] = url } else if apps.count < 6 { apps.append(url) }
        save()
    }

    func remove(_ url: URL) {
        apps.removeAll { $0 == url }
        save()
    }

    private func save() {
        UserDefaults.standard.set(apps.map(\.path), forKey: "launcherApps")
    }

    static func name(_ url: URL) -> String {
        FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
    }

    static func icon(_ url: URL) -> NSImage { NSWorkspace.shared.icon(forFile: url.path) }
}
